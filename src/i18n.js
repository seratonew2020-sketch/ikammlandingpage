const STORAGE_KEY = "ikamm-lang";

function detectInitial() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && messages[saved]) return saved;
  } catch {}
  const nav = (navigator.language || "th").toLowerCase();
  if (nav.startsWith("zh")) return "zh";
  if (nav.startsWith("en")) return "en";
  return "th";
}

export const locale = ref(detectInitial());
export const t = computed(() => messages[locale.value]);
export const currentLanguage = computed(() => languages.find((l) => l.code === locale.value));

export function setLocale(code) {
  if (messages[code]) locale.value = code;
}

function applyDocumentLang() {
  const lang = currentLanguage.value;
  document.documentElement.lang = lang.htmlLang;
  document.title = t.value.meta.title;
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", t.value.meta.description);
  try {
    localStorage.setItem(STORAGE_KEY, locale.value);
  } catch {}
}

watch(locale, applyDocumentLang, { immediate: true });

